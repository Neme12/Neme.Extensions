using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using System.Globalization;
using System.Text;

namespace Neme.Extensions.SourceGenerators;

public abstract class AbstractEnumGenerator
{
    private static readonly SymbolDisplayFormat s_fullyQualifiedMinimalFormat = new(
        SymbolDisplayGlobalNamespaceStyle.Omitted,
        SymbolDisplayTypeQualificationStyle.NameAndContainingTypesAndNamespaces,
        SymbolDisplayGenericsOptions.None,
        SymbolDisplayMemberOptions.IncludeContainingType);

    protected static INamedTypeSymbol? GetEnumSymbol(GeneratorSyntaxContext context, CancellationToken cancellationToken)
    {
        cancellationToken.ThrowIfCancellationRequested();

        var enumDeclaration = (EnumDeclarationSyntax)context.Node;
        return context.SemanticModel.GetDeclaredSymbol(enumDeclaration) as INamedTypeSymbol;
    }

    protected static bool IsAccessibleFromNamespaceLevel(INamedTypeSymbol enumType)
    {
        if (!IsNamespaceVisible(enumType.DeclaredAccessibility))
            return false;

        for (var containingType = enumType.ContainingType; containingType is not null; containingType = containingType.ContainingType)
        {
            if (!IsNamespaceVisible(containingType.DeclaredAccessibility))
                return false;
        }

        return true;
    }

    private static bool IsNamespaceVisible(Accessibility accessibility) =>
        accessibility is Accessibility.Public or Accessibility.Internal or Accessibility.ProtectedAndInternal;

    protected static string GetFileName(INamedTypeSymbol enumType, string suffix)
    {
        var fullyQualifiedName = enumType.ToDisplayString(s_fullyQualifiedMinimalFormat);

        var hintNameBuilder = new StringBuilder(fullyQualifiedName.Length);

        foreach (var character in fullyQualifiedName)
            hintNameBuilder.Append(char.IsLetterOrDigit(character) ? character : '_');

        return string.Create(CultureInfo.InvariantCulture, $"""{hintNameBuilder}{suffix}.g.cs""");
    }

    protected static string GetGeneratedClassSource(
        string? @namespace,
        string className,
        string memberSource,
        bool isPartial,
        bool emitAttribute,
        string generatorName,
        CancellationToken cancellationToken)
    {
        var namespaceDeclaration = @namespace is null
            ? ""
            : string.Create(CultureInfo.InvariantCulture, $"""

                namespace {@namespace};

                """);

        cancellationToken.ThrowIfCancellationRequested();

        var attributeDeclaration = emitAttribute
            ? $"""
            
            [global::System.CodeDom.Compiler.GeneratedCode("Neme.Extensions.SourceGenerators.{generatorName}", "0.0.0.0")]
            """
            : "";

        var result =
            // lang=c#
            $$"""
            // <auto-generated/>
            {{namespaceDeclaration}}
            #nullable enable
            {{attributeDeclaration}}      
            internal static {{(isPartial ? "partial " : "")}}class {{className}}
            {
            {{memberSource}}
            }

            """;

        cancellationToken.ThrowIfCancellationRequested();

        return result;
    }
}
