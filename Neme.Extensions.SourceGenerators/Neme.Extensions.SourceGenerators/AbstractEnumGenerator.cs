using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using System.Globalization;
using System.Runtime.CompilerServices;
using System.Text;

namespace Neme.Extensions.SourceGenerators;

public abstract class AbstractEnumGenerator
{
    private static readonly SymbolDisplayFormat s_fullyQualifiedMinimalFormat = new(
        SymbolDisplayGlobalNamespaceStyle.Omitted,
        SymbolDisplayTypeQualificationStyle.NameAndContainingTypesAndNamespaces,
        SymbolDisplayGenericsOptions.None,
        SymbolDisplayMemberOptions.IncludeContainingType);

    protected static INamedTypeSymbol? GetEnumSymbol(GeneratorSyntaxContext context, CancellationToken cancellationToken)
    {
        cancellationToken.ThrowIfCancellationRequested();

        var enumDeclaration = (EnumDeclarationSyntax)context.Node;
        return context.SemanticModel.GetDeclaredSymbol(enumDeclaration) as INamedTypeSymbol;
    }

    protected static bool IsAccessibleFromNamespaceLevel(INamedTypeSymbol enumType)
    {
        if (!IsNamespaceVisible(enumType.DeclaredAccessibility))
            return false;

        for (var containingType = enumType.ContainingType; containingType is not null; containingType = containingType.ContainingType)
        {
            if (!IsNamespaceVisible(containingType.DeclaredAccessibility))
                return false;
        }

        return true;
    }

    private static bool IsNamespaceVisible(Accessibility accessibility) =>
        accessibility is Accessibility.Public or Accessibility.Internal or Accessibility.ProtectedAndInternal;

    protected static string GetFileName(INamedTypeSymbol enumType, string suffix)
    {
        var fullyQualifiedName = enumType.ToDisplayString(s_fullyQualifiedMinimalFormat);

        var hintNameBuilder = new StringBuilder(fullyQualifiedName.Length);

        foreach (var character in fullyQualifiedName)
            hintNameBuilder.Append(char.IsLetterOrDigit(character) ? character : '_');

        return Invariant($"""{hintNameBuilder}{suffix}.g.cs""");
    }

    protected static string GetGeneratedClassSource(
        string? @namespace,
        string className,
        string memberSource,
        bool isPartial,
        bool emitAttribute,
        string generatorName,
        CancellationToken cancellationToken)
    {
        var namespaceDeclarationBuilder = new DefaultInterpolatedStringHandler(literalLength: 32, formattedCount: 0, CultureInfo.InvariantCulture, stackalloc char[32]);

        if (@namespace is not null)
        {
            namespaceDeclarationBuilder.AppendLiteral(Environment.NewLine);
            namespaceDeclarationBuilder.AppendFormatted(@namespace);
            namespaceDeclarationBuilder.AppendLiteral(";");
            namespaceDeclarationBuilder.AppendLiteral(Environment.NewLine);

        }

        cancellationToken.ThrowIfCancellationRequested();

        var attributeDeclarationBuilder = new DefaultInterpolatedStringHandler(literalLength: 128, formattedCount: 0, CultureInfo.InvariantCulture, stackalloc char[128]);

        if (emitAttribute)
        {
            attributeDeclarationBuilder.AppendLiteral(Environment.NewLine);
            attributeDeclarationBuilder.AppendLiteral("[global::System.CodeDom.Compiler.GeneratedCode(global::Neme.Extensions.SourceGenerators.");
            attributeDeclarationBuilder.AppendFormatted(generatorName);
            attributeDeclarationBuilder.AppendLiteral(", 0.0.0.0)]");
        }

        var resultBuilder = new DefaultInterpolatedStringHandler(literalLength: 1024, formattedCount: 0, CultureInfo.InvariantCulture);
        resultBuilder.AppendLiteral(Environment.NewLine);
        resultBuilder.AppendLiteral("// <auto-generated/>");
        resultBuilder.AppendLiteral(Environment.NewLine);
        resultBuilder.AppendFormatted(namespaceDeclarationBuilder.ToStringAndClear());
        resultBuilder.AppendLiteral("#nullable enable");
        resultBuilder.AppendLiteral(Environment.NewLine);
        resultBuilder.AppendFormatted(attributeDeclarationBuilder.ToStringAndClear());
        resultBuilder.AppendLiteral(Environment.NewLine);
        resultBuilder.AppendLiteral("internal static ");

        if (isPartial)
            resultBuilder.AppendLiteral("partial ");

        resultBuilder.AppendLiteral("class ");
        resultBuilder.AppendFormatted(className);
        resultBuilder.AppendLiteral(Environment.NewLine);
        resultBuilder.AppendLiteral("{");
        resultBuilder.AppendLiteral(Environment.NewLine);
        resultBuilder.AppendFormatted(memberSource);
        resultBuilder.AppendLiteral(Environment.NewLine);
        resultBuilder.AppendLiteral("}");
        resultBuilder.AppendLiteral(Environment.NewLine);

        cancellationToken.ThrowIfCancellationRequested();

        return resultBuilder.ToStringAndClear();
    }
}
