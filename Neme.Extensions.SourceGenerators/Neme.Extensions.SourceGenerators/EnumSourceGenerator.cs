using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using System.CodeDom.Compiler;
using System.Globalization;
using System.Text;
using static System.FormattableString;

namespace Neme.Extensions.SourceGenerators;

#pragma warning disable RS1038 // The package is installed
[Generator(LanguageNames.CSharp)]
#pragma warning restore RS1038
public sealed class EnumSourceGenerator : IIncrementalGenerator
{
    private static readonly SymbolDisplayFormat s_fullyQualifiedMinimalFormat = new(
        SymbolDisplayGlobalNamespaceStyle.Omitted,
        SymbolDisplayTypeQualificationStyle.NameAndContainingTypesAndNamespaces,
        SymbolDisplayGenericsOptions.None,
        SymbolDisplayMemberOptions.IncludeContainingType);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var enumSymbols = context.SyntaxProvider
            .CreateSyntaxProvider(
                static (node, _) => node is EnumDeclarationSyntax,
                static (syntaxContext, cancellationToken) => GetEnumSymbol(syntaxContext, cancellationToken))
            .Where(static symbol => symbol is INamedTypeSymbol enumSymbol && IsAccessibleFromNamespaceLevel(enumSymbol));

        context.RegisterSourceOutput(enumSymbols, static (sourceContext, enumSymbol) => EmitEnumSource(sourceContext, enumSymbol!, sourceContext.CancellationToken));
    }

    private static INamedTypeSymbol? GetEnumSymbol(GeneratorSyntaxContext context, CancellationToken cancellationToken)
    {
        cancellationToken.ThrowIfCancellationRequested();

        var enumDeclaration = (EnumDeclarationSyntax)context.Node;
        return context.SemanticModel.GetDeclaredSymbol(enumDeclaration) as INamedTypeSymbol;
    }

    private static void EmitEnumSource(
        SourceProductionContext context,
        INamedTypeSymbol enumSymbol,
        CancellationToken cancellationToken)
    {
        cancellationToken.ThrowIfCancellationRequested();

        var enumTypeName = enumSymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var namespaceDeclaration = enumSymbol.ContainingNamespace.IsGlobalNamespace
            ? Environment.NewLine
            : Invariant($"namespace {enumSymbol.ContainingNamespace.ToDisplayString()};{Environment.NewLine}");
        var extensionClassName = GetExtensionClassName(enumSymbol);

        cancellationToken.ThrowIfCancellationRequested();

        var enumMembers = enumSymbol
            .GetMembers()
            .OfType<IFieldSymbol>()
            .Where(static field => field.HasConstantValue)
            .ToImmutableArray();

        var switchWriter = new IndentedTextWriter(new StringWriter(CultureInfo.InvariantCulture));
        var baselineIndent = 2;

        switchWriter.WriteLine("value switch");
        switchWriter.Indent = baselineIndent;
        switchWriter.WriteLine("{");
        switchWriter.Indent = baselineIndent + 1;

        foreach (var member in enumMembers)
        {
            switchWriter.WriteLine($"{enumTypeName}.{member.Name} => nameof({enumTypeName}.{member.Name}),");
        }

        switchWriter.WriteLine("_ => value.ToString(),");

        switchWriter.Indent = baselineIndent;
        switchWriter.Write("}");

        switchWriter.Flush();

        cancellationToken.ThrowIfCancellationRequested();

        var switchSource = switchWriter.InnerWriter.ToString();

        var extensionSource =
            // lang=c#
            $$"""
                extension({{enumTypeName}} value)
                {
                    public string Name => {{switchSource}};
                }
            """;

        var source =
            // lang=c
            $$"""
            // <auto-generated/>
            {{namespaceDeclaration}}
            [global::System.CodeDom.Compiler.GeneratedCode("Neme.Extensions.SourceGenerators", "1.0.0.0")]
            internal static class {{extensionClassName}}
            {
            {{extensionSource}}
            }
            """;

        cancellationToken.ThrowIfCancellationRequested();

        context.AddSource(GetHintName(enumSymbol), SourceText.From(source, Encoding.UTF8));
    }

    private static string GetExtensionClassName(INamedTypeSymbol enumSymbol)
    {
        var containingTypes = new Stack<string>();
        for (var containingType = enumSymbol.ContainingType; containingType is not null; containingType = containingType.ContainingType)
            containingTypes.Push(containingType.Name);

        var typePrefix = containingTypes.Count == 0
            ? ""
            : Invariant($"{string.Join("_", containingTypes)}_");
        return Invariant($"{typePrefix}{enumSymbol.Name}Extensions");
    }

    private static bool IsAccessibleFromNamespaceLevel(INamedTypeSymbol enumSymbol)
    {
        if (!IsNamespaceVisible(enumSymbol.DeclaredAccessibility))
            return false;

        for (var containingType = enumSymbol.ContainingType; containingType is not null; containingType = containingType.ContainingType)
        {
            if (!IsNamespaceVisible(containingType.DeclaredAccessibility))
                return false;
        }

        return true;
    }

    private static bool IsNamespaceVisible(Accessibility accessibility) =>
        accessibility is Accessibility.Public or Accessibility.Internal;

    private static string GetHintName(INamedTypeSymbol enumSymbol)
    {
        var fullyQualifiedName = enumSymbol.ToDisplayString(s_fullyQualifiedMinimalFormat);

        var hintNameBuilder = new StringBuilder(fullyQualifiedName.Length);

        foreach (var character in fullyQualifiedName)
            hintNameBuilder.Append(char.IsLetterOrDigit(character) ? character : '_');

        return Invariant($"{hintNameBuilder}.g.cs");
    }
}
